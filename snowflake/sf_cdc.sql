CREATE DATABASE IF NOT EXISTS INVENTORY_CDC_DB;
CREATE SCHEMA IF NOT EXISTS INVENTORY_CDC_DB.BRONZE;

USE SCHEMA INVENTORY_CDC_DB.BRONZE;

-- Create Raw Bronze Table (holds unparsed VARIANT JSON)
CREATE OR REPLACE TABLE RAW_INVENTORY_CDC (
    raw_payload VARIANT,
    file_name STRING,
    file_row_number NUMBER,
    ingested_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Create File Format for JSON
CREATE OR REPLACE FILE FORMAT JSON_FILE_FORMAT
    TYPE = 'JSON'
    STRIP_OUTER_ARRAY = TRUE
    IGNORE_UTF8_ERRORS = TRUE;

CREATE OR REPLACE STORAGE INTEGRATION s3_cdc_integration
    TYPE = EXTERNAL_STAGE
    STORAGE_PROVIDER = 'S3'
    ENABLED = TRUE
    STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::097853038822:role/SnowflakeS3CDCRole'
    STORAGE_ALLOWED_LOCATIONS = ('s3://cdc-inventory-sf/raw-cdc-data/');

-- Retrieve the IAM User & External ID generated by Snowflake
DESC INTEGRATION s3_cdc_integration;

-- Create External Stage linked to S3 and Storage Integration
CREATE OR REPLACE STAGE cdc_s3_stage
    URL = 's3://cdc-inventory-sf/raw-cdc-data/'
    STORAGE_INTEGRATION = s3_cdc_integration
    FILE_FORMAT = JSON_FILE_FORMAT;

-- Create Snowpipe targeting the Bronze Table
CREATE OR REPLACE PIPE raw_inventory_cdc_pipe
    AUTO_INGEST = TRUE
    AS
    COPY INTO INVENTORY_CDC_DB.BRONZE.RAW_INVENTORY_CDC (raw_payload, file_name, file_row_number)
    FROM (
        SELECT 
            $1,
            METADATA$FILENAME,
            METADATA$FILE_ROW_NUMBER
        FROM @cdc_s3_stage
    );

-- Retrieve the SQS Queue ARN for S3 Notification setup
SHOW PIPES LIKE 'raw_inventory_cdc_pipe';

CREATE SCHEMA IF NOT EXISTS INVENTORY_CDC_DB.SILVER;
USE SCHEMA INVENTORY_CDC_DB.SILVER;

-- 1. Silver Table: Strongly typed with business columns
CREATE OR REPLACE TABLE INVENTORY_SILVER (
    event_id STRING,
    event_type STRING,
    event_timestamp TIMESTAMP_NTZ,
    seller_id STRING,
    product_id STRING,
    product_name STRING,
    category STRING,
    stock_quantity NUMBER,
    unit_price NUMBER(10, 2),
    warehouse_location STRING,
    is_deleted BOOLEAN DEFAULT FALSE,
    updated_at TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE STREAM INVENTORY_CDC_DB.BRONZE.BRONZE_CDC_STREAM 
    ON TABLE INVENTORY_CDC_DB.BRONZE.RAW_INVENTORY_CDC;

CREATE OR REPLACE TASK PROCESS_BRONZE_TO_SILVER_TASK
    WAREHOUSE = COMPUTE_WH
    SCHEDULE = '1 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('INVENTORY_CDC_DB.BRONZE.BRONZE_CDC_STREAM')
AS
MERGE INTO INVENTORY_CDC_DB.SILVER.INVENTORY_SILVER target
USING (
    WITH parsed_stream AS (
        SELECT 
            raw_payload:event_id::STRING AS event_id,
            raw_payload:event_type::STRING AS event_type,
            raw_payload:event_timestamp::TIMESTAMP_NTZ AS event_timestamp,
            raw_payload:payload.seller_id::STRING AS seller_id,
            raw_payload:payload.product_id::STRING AS product_id,
            raw_payload:payload.product_name::STRING AS product_name,
            raw_payload:payload.category::STRING AS category,
            raw_payload:payload.stock_quantity::NUMBER AS stock_quantity,
            raw_payload:payload.unit_price::NUMBER(10, 2) AS unit_price,
            raw_payload:payload.warehouse_location::STRING AS warehouse_location,
            ROW_NUMBER() OVER (
                PARTITION BY raw_payload:payload.seller_id::STRING, raw_payload:payload.product_id::STRING 
                ORDER BY raw_payload:event_timestamp::TIMESTAMP_NTZ DESC
            ) as rn
        FROM INVENTORY_CDC_DB.BRONZE.BRONZE_CDC_STREAM
        WHERE METADATA$ACTION = 'INSERT' -- Process new streaming inserts from pipe
    )
    SELECT * FROM parsed_stream WHERE rn = 1
) source
ON target.seller_id = source.seller_id AND target.product_id = source.product_id
WHEN MATCHED AND source.event_type = 'DELETE' THEN 
    UPDATE SET target.is_deleted = TRUE, target.updated_at = CURRENT_TIMESTAMP()
WHEN MATCHED AND source.event_type IN ('INSERT', 'UPDATE') THEN 
    UPDATE SET 
        target.product_name = source.product_name,
        target.category = source.category,
        target.stock_quantity = source.stock_quantity,
        target.unit_price = source.unit_price,
        target.warehouse_location = source.warehouse_location,
        target.event_type = source.event_type,
        target.event_timestamp = source.event_timestamp,
        target.is_deleted = FALSE,
        target.updated_at = CURRENT_TIMESTAMP()
WHEN NOT MATCHED AND source.event_type != 'DELETE' THEN 
    INSERT (event_id, event_type, event_timestamp, seller_id, product_id, product_name, category, stock_quantity, unit_price, warehouse_location, is_deleted, updated_at)
    VALUES (source.event_id, source.event_type, source.event_timestamp, source.seller_id, source.product_id, source.product_name, source.category, source.stock_quantity, source.unit_price, source.warehouse_location, FALSE, CURRENT_TIMESTAMP());

select * from INVENTORY_CDC_DB.SILVER.INVENTORY_SILVER; 

CREATE SCHEMA IF NOT EXISTS INVENTORY_CDC_DB.GOLD;
USE SCHEMA INVENTORY_CDC_DB.GOLD;

-- 1. Gold Summary Table
CREATE OR REPLACE TABLE SELLER_INVENTORY_SUMMARY_GOLD (
    seller_id STRING,
    category STRING,
    total_products NUMBER,
    total_stock_quantity NUMBER,
    avg_unit_price NUMBER(10, 2),
    last_updated TIMESTAMP_NTZ
);

CREATE OR REPLACE STREAM INVENTORY_CDC_DB.SILVER.SILVER_INVENTORY_STREAM 
    ON TABLE INVENTORY_CDC_DB.SILVER.INVENTORY_SILVER;

-- Tasks in a graph must live in the same schema, so this task is created in SILVER
CREATE OR REPLACE TASK INVENTORY_CDC_DB.SILVER.PROCESS_SILVER_TO_GOLD_TASK
    WAREHOUSE = COMPUTE_WH
    AFTER INVENTORY_CDC_DB.SILVER.PROCESS_BRONZE_TO_SILVER_TASK
    WHEN SYSTEM$STREAM_HAS_DATA('INVENTORY_CDC_DB.SILVER.SILVER_INVENTORY_STREAM')
AS
MERGE INTO INVENTORY_CDC_DB.GOLD.SELLER_INVENTORY_SUMMARY_GOLD target
USING (
    SELECT 
        seller_id,
        category,
        COUNT(DISTINCT product_id) AS total_products,
        SUM(stock_quantity) AS total_stock_quantity,
        ROUND(AVG(unit_price), 2) AS avg_unit_price,
        MAX(updated_at) AS last_updated
    FROM INVENTORY_CDC_DB.SILVER.INVENTORY_SILVER
    WHERE is_deleted = FALSE
    GROUP BY seller_id, category
) source
ON target.seller_id = source.seller_id AND target.category = source.category
WHEN MATCHED THEN 
    UPDATE SET 
        target.total_products = source.total_products,
        target.total_stock_quantity = source.total_stock_quantity,
        target.avg_unit_price = source.avg_unit_price,
        target.last_updated = source.last_updated
WHEN NOT MATCHED THEN 
    INSERT (seller_id, category, total_products, total_stock_quantity, avg_unit_price, last_updated)
    VALUES (source.seller_id, source.category, source.total_products, source.total_stock_quantity, source.avg_unit_price, source.last_updated);

-- 4. Enable both Tasks (child first, then root)
ALTER TASK INVENTORY_CDC_DB.SILVER.PROCESS_SILVER_TO_GOLD_TASK RESUME;
ALTER TASK INVENTORY_CDC_DB.SILVER.PROCESS_BRONZE_TO_SILVER_TASK RESUME;
ALTER TASK INVENTORY_CDC_DB.SILVER.PROCESS_BRONZE_TO_SILVER_TASK SUSPEND;

